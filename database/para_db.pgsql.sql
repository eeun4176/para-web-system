-- Para database for Supabase (PostgreSQL).
-- Converted from the phpMyAdmin/MariaDB dump (para_db.sql, Oct 31 2026).
-- Creates the whole Para database (tables, keys, starting fares) on an empty Supabase / PostgreSQL database.
-- PHP connects as the "postgres" role, which bypasses Row Level Security;
-- RLS is enabled with no policies so Supabase's public REST API cannot read these tables.

BEGIN;

-- ---------- Lookup tables ----------

CREATE TABLE passenger_types (
  code          VARCHAR(20)  PRIMARY KEY,
  label         VARCHAR(40)  NOT NULL,
  discount_rate DECIMAL(3,2) NOT NULL DEFAULT 0.00,
  is_active     SMALLINT     NOT NULL DEFAULT 1,
  is_deleted    SMALLINT     NOT NULL DEFAULT 0   -- 1 = deleted by the admin but kept because saved trips or favorites use it
);

CREATE TABLE transport_types (
  code          VARCHAR(30)  PRIMARY KEY,
  label         VARCHAR(60)  NOT NULL,
  base_fare     DECIMAL(6,2) NOT NULL,
  base_km       DECIMAL(4,1) NOT NULL,
  excess_per_km DECIMAL(6,2) NOT NULL,
  avg_speed_kph DECIMAL(5,2) NOT NULL DEFAULT 20.00,
  is_active     SMALLINT     NOT NULL DEFAULT 1,
  is_deleted    SMALLINT     NOT NULL DEFAULT 0   -- 1 = deleted by the admin but kept because saved trips or favorites use it
);

-- ---------- Users ----------

CREATE TABLE users (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              VARCHAR(100) NOT NULL,
  email             VARCHAR(255) UNIQUE,            -- NULL for the admin, who signs in with an account key
  account_key       VARCHAR(40)  UNIQUE,            -- admin sign-in name (e.g. ParaAdmin), see admin-login.html
  password_hash     VARCHAR(255) DEFAULT NULL,   -- NULL when the user signs in only with Google or an email code
  google_sub        VARCHAR(255) UNIQUE,         -- Google account ID ("sub"), set on first Google sign-in
  email_verified    SMALLINT     NOT NULL DEFAULT 0,  -- 1 once the user proved they own the email (email code or Google)
  profile_picture   VARCHAR(255) DEFAULT NULL,
  avatar            BYTEA        DEFAULT NULL,   -- profile picture bytes (Vercel has no writable disk)
  avatar_mime       VARCHAR(20)  DEFAULT NULL,
  role              VARCHAR(10)  NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  created_at        TIMESTAMP(0)    NOT NULL DEFAULT now(),
  default_passenger VARCHAR(20)  DEFAULT NULL,
  default_transport VARCHAR(30)  DEFAULT NULL,
  CONSTRAINT users_email_or_key CHECK (email IS NOT NULL OR account_key IS NOT NULL)
);

-- ---------- User data ----------

CREATE TABLE landmarks (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INT          DEFAULT NULL REFERENCES users (id) ON DELETE CASCADE,
  name        VARCHAR(150) NOT NULL,
  category    VARCHAR(20)  NOT NULL DEFAULT 'other'
              CHECK (category IN ('school','hospital','terminal','market','church','park','food','other')),
  description TEXT         DEFAULT NULL,
  is_public   SMALLINT     NOT NULL DEFAULT 0,
  lat         DECIMAL(9,6) NOT NULL,
  lng         DECIMAL(9,6) NOT NULL,
  created_at  TIMESTAMP(0)    NOT NULL DEFAULT now()
);
CREATE INDEX idx_landmarks_user ON landmarks (user_id);

CREATE TABLE favorite_routes (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        INT          NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  label          VARCHAR(100) NOT NULL,
  origin_name    VARCHAR(200) NOT NULL,
  origin_lat     DECIMAL(9,6) NOT NULL,
  origin_lng     DECIMAL(9,6) NOT NULL,
  dest_name      VARCHAR(200) NOT NULL,
  dest_lat       DECIMAL(9,6) NOT NULL,
  dest_lng       DECIMAL(9,6) NOT NULL,
  transport_code VARCHAR(30)  NOT NULL REFERENCES transport_types (code) ON UPDATE CASCADE,
  passenger_code VARCHAR(20)  NOT NULL REFERENCES passenger_types (code) ON UPDATE CASCADE,
  created_at     TIMESTAMP(0)    NOT NULL DEFAULT now()
);
CREATE INDEX idx_fav_user ON favorite_routes (user_id);
CREATE INDEX fk_fav_transport ON favorite_routes (transport_code);
CREATE INDEX fk_fav_passenger ON favorite_routes (passenger_code);

CREATE TABLE trips (
  id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        INT          NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  origin_name    VARCHAR(200) NOT NULL,
  origin_lat     DECIMAL(9,6) NOT NULL,
  origin_lng     DECIMAL(9,6) NOT NULL,
  dest_name      VARCHAR(200) NOT NULL,
  dest_lat       DECIMAL(9,6) NOT NULL,
  dest_lng       DECIMAL(9,6) NOT NULL,
  transport_code VARCHAR(30)  NOT NULL REFERENCES transport_types (code) ON UPDATE CASCADE,
  passenger_code VARCHAR(20)  NOT NULL REFERENCES passenger_types (code) ON UPDATE CASCADE,
  distance_km    DECIMAL(6,2) NOT NULL,
  total_fare     DECIMAL(7,2) NOT NULL,
  duration_min   SMALLINT     NOT NULL CHECK (duration_min >= 0),
  created_at     TIMESTAMP(0)    NOT NULL DEFAULT now()
);
CREATE INDEX idx_trips_user_date ON trips (user_id, created_at);
CREATE INDEX fk_trips_transport ON trips (transport_code);
CREATE INDEX fk_trips_passenger ON trips (passenger_code);

-- ---------- Security / admin ----------

CREATE TABLE login_attempts (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email        VARCHAR(255) NOT NULL,
  ip           VARCHAR(45)  NOT NULL,
  attempted_at TIMESTAMP(0)    NOT NULL DEFAULT now()
);
CREATE INDEX idx_attempts ON login_attempts (email, ip, attempted_at);

-- One-time 6-digit codes sent by email: log in / sign up ('login') or confirm a new email ('change_email').
-- Only a hash of the code is kept. A code works once, for 10 minutes, and is cancelled after 5 wrong tries.
CREATE TABLE login_codes (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      VARCHAR(255) NOT NULL,
  user_id    INT          DEFAULT NULL REFERENCES users (id) ON DELETE CASCADE,   -- set for 'change_email'
  purpose    VARCHAR(20)  NOT NULL CHECK (purpose IN ('login', 'change_email')),
  code_hash  CHAR(64)     NOT NULL,
  attempts   SMALLINT     NOT NULL DEFAULT 0,
  expires_at TIMESTAMP(0) NOT NULL,
  used_at    TIMESTAMP(0) DEFAULT NULL,
  ip         VARCHAR(45)  NOT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT now()
);
CREATE INDEX idx_login_codes_email ON login_codes (email, purpose, created_at);

-- Request counters for rate limits (email checks, code sends), kept for a day
CREATE TABLE rate_limits (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action     VARCHAR(30)  NOT NULL,
  ident      VARCHAR(255) NOT NULL,   -- an email or an IP address
  created_at TIMESTAMP(0) NOT NULL DEFAULT now()
);
CREATE INDEX idx_rate_limits ON rate_limits (action, ident, created_at);

CREATE TABLE audit_log (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id   INT          DEFAULT NULL REFERENCES users (id) ON DELETE SET NULL,
  admin_name VARCHAR(100) NOT NULL,
  action     VARCHAR(40)  NOT NULL,
  target     VARCHAR(150) NOT NULL,
  details    VARCHAR(500) DEFAULT NULL,
  created_at TIMESTAMP(0)    NOT NULL DEFAULT now()
);
CREATE INDEX fk_audit_admin ON audit_log (admin_id);
CREATE INDEX idx_audit_date ON audit_log (created_at);

-- PHP sessions (Vercel runs each request on a fresh server, so file sessions are lost)
CREATE TABLE php_sessions (
  id         VARCHAR(128) PRIMARY KEY,
  data       TEXT         NOT NULL,
  updated_at INT          NOT NULL
);
CREATE INDEX idx_sessions_updated ON php_sessions (updated_at);

