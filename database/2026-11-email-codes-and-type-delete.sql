-- Migration (November 2026): email-code login replaces the recovery code, and the admin can delete used fare types.
-- Run once in the Supabase SQL Editor before deploying the new version. Safe to run twice.
--   * users.email_verified: 1 once the user proved they own the email (email code or Google)
--   * login_codes: one-time 6-digit codes sent by email (only their hash is stored)
--   * rate_limits: request counters for the email check and code sending
--   * password_reset_tokens (the old recovery codes) is removed
--   * transport_types / passenger_types.is_deleted: a deleted type that saved trips still use is hidden, not removed

BEGIN;

ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified SMALLINT NOT NULL DEFAULT 0;
UPDATE users SET email_verified = 1 WHERE google_sub IS NOT NULL;   -- Google already confirmed these emails

CREATE TABLE IF NOT EXISTS login_codes (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      VARCHAR(255) NOT NULL,
  user_id    INT          DEFAULT NULL REFERENCES users (id) ON DELETE CASCADE,
  purpose    VARCHAR(20)  NOT NULL CHECK (purpose IN ('login', 'change_email')),
  code_hash  CHAR(64)     NOT NULL,
  attempts   SMALLINT     NOT NULL DEFAULT 0,
  expires_at TIMESTAMP(0) NOT NULL,
  used_at    TIMESTAMP(0) DEFAULT NULL,
  ip         VARCHAR(45)  NOT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_login_codes_email ON login_codes (email, purpose, created_at);

CREATE TABLE IF NOT EXISTS rate_limits (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action     VARCHAR(30)  NOT NULL,
  ident      VARCHAR(255) NOT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rate_limits ON rate_limits (action, ident, created_at);

-- Block Supabase's public REST API (PHP connects as the owner and is not affected)
ALTER TABLE login_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE rate_limits ENABLE ROW LEVEL SECURITY;

DROP TABLE IF EXISTS password_reset_tokens;

ALTER TABLE transport_types ADD COLUMN IF NOT EXISTS is_deleted SMALLINT NOT NULL DEFAULT 0;
ALTER TABLE passenger_types ADD COLUMN IF NOT EXISTS is_deleted SMALLINT NOT NULL DEFAULT 0;

COMMIT;
